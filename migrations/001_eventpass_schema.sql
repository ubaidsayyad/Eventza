CREATE TABLE IF NOT EXISTS ep_events (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 name TEXT NOT NULL,
 slug TEXT NOT NULL UNIQUE,
 category TEXT NOT NULL DEFAULT 'community',
 short_description TEXT NOT NULL DEFAULT '',
 description TEXT NOT NULL DEFAULT '',
 banner_url TEXT,
 venue TEXT NOT NULL DEFAULT 'Venue to be announced',
 address TEXT NOT NULL DEFAULT '',
 city TEXT NOT NULL DEFAULT '',
 event_date DATE NOT NULL,
 start_time TIME NOT NULL DEFAULT '18:00',
 end_time TIME NOT NULL DEFAULT '21:00',
 sales_start TIMESTAMPTZ NOT NULL DEFAULT now(),
 sales_end TIMESTAMPTZ,
 total_capacity INTEGER NOT NULL DEFAULT 0 CHECK (total_capacity >= 0),
 event_status TEXT NOT NULL DEFAULT 'draft' CHECK (event_status IN ('draft','published','unpublished','archived')),
 is_sample BOOLEAN NOT NULL DEFAULT false,
 attendee_names_required BOOLEAN NOT NULL DEFAULT false,
 attendee_emails_allowed BOOLEAN NOT NULL DEFAULT false,
 age_restriction TEXT NOT NULL DEFAULT 'All ages',
 entry_instructions TEXT NOT NULL DEFAULT 'Please carry your ticket QR pass for entry.',
 cancellation_policy TEXT NOT NULL DEFAULT 'Tickets are subject to the organizer cancellation policy.',
 terms TEXT NOT NULL DEFAULT '',
 created_by TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);